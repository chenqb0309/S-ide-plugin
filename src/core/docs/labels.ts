/** 產出文件的語言。只影響「人看的字」，不影響 anchor 與結構。 */
export type DocLang = 'en' | 'zh-TW';

export interface DocLabels {
  toc: string;
  calls: string;
  propsHeading: string;
  colName: string;
  colType: string;
  indexTitle: string;
  indexNote: string;
  colFile: string;
  colClasses: string;
  fileNote: string;
}

const EN: DocLabels = {
  toc: 'Classes',
  calls: 'Calls',
  propsHeading: 'Properties',
  colName: 'Name',
  colType: 'Type',
  indexTitle: 'Semantic Docs Index',
  indexNote: 'Generated by S-IDE. Lists files and classes only; open a file for details.',
  colFile: 'File',
  colClasses: 'Classes',
  fileNote: 'Generated from source by S-IDE. Do not edit manually; run "S-IDE: Sync Semantic Docs" after changing code.',
};

const ZH_TW: DocLabels = {
  toc: '類別',
  calls: '呼叫',
  propsHeading: '屬性一覽',
  colName: '名稱',
  colType: '型別',
  indexTitle: '語義文件索引',
  indexNote: '由 S-IDE 產生。這裡只列檔案與類別，內容請點進各檔案。',
  colFile: '檔案',
  colClasses: '類別',
  fileNote: '本檔由 S-IDE 從原始碼產生。**請勿手動編輯**；改完 code 後執行「S-IDE: 同步語義文件」。',
};

export function labelsFor(lang: string | undefined): DocLabels {
  return lang === 'zh-TW' ? ZH_TW : EN;
}
